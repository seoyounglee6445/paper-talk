function parseCsv(csvText) {
  const text = String(csvText || "").replace(/^\uFEFF/, "");
  const rows = [];
  let row = [];
  let value = "";
  let inQuotes = false;

  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    const next = text[i + 1];

    if (char === '"') {
      if (inQuotes && next === '"') {
        value += '"';
        i++;
      } else {
        inQuotes = !inQuotes;
      }
      continue;
    }

    if (char === "," && !inQuotes) {
      row.push(value);
      value = "";
      continue;
    }

    if ((char === "\n" || char === "\r") && !inQuotes) {
      if (char === "\r" && next === "\n") i++;
      row.push(value);
      rows.push(row);
      row = [];
      value = "";
      continue;
    }

    value += char;
  }

  row.push(value);
  rows.push(row);

  const nonEmptyRows = rows.filter(r =>
    r.some(cell => String(cell || "").trim())
  );

  if (nonEmptyRows.length < 2) return [];

  const headers = nonEmptyRows[0].map(h => String(h || "").trim());

  return nonEmptyRows.slice(1).map(cells => {
    const obj = {};
    headers.forEach((header, index) => {
      obj[header || `column_${index}`] = String(cells[index] || "").trim();
    });
    return obj;
  });
}

function normalizeLinkedInRow(row) {
  const keys = Object.keys(row || {});
  const lowerMap = {};

  for (const key of keys) {
    lowerMap[key.toLowerCase().replace(/[\s_\-]/g, "")] = key;
  }

  function pick(possibleNames) {
    for (const name of possibleNames) {
      const normalized = name.toLowerCase().replace(/[\s_\-]/g, "");
      const realKey = lowerMap[normalized];

      if (realKey && String(row[realKey] || "").trim()) {
        return String(row[realKey]).trim();
      }
    }

    return "";
  }

  const commentary = pick([
    "ShareCommentary",
    "Share Commentary",
    "Commentary",
    "Text",
    "Content",
    "Post",
    "Post Text",
    "Update Text",
    "Body",
    "Description"
  ]);

  const title = pick([
    "Title",
    "Article Title",
    "Post Title",
    "Headline"
  ]);

  const date = pick([
    "Date",
    "Created Date",
    "Creation Date",
    "Created At",
    "Time"
  ]);

  const sourceUrl = pick([
    "ShareLink",
    "Share Link",
    "URL",
    "Url",
    "Post URL",
    "Post Url",
    "Link",
    "Permalink"
  ]) || extractFirstUrl(commentary);

  const pdfLink = extractDoiOrPdfLink(commentary + "\n" + sourceUrl);

  const allText = keys
    .map(key => String(row[key] || "").trim())
    .filter(Boolean)
    .join("\n");

  const content = commentary || allText;

  return {
    title: title || makeTitleFromText(content),
    date,
    sourceUrl,
    pdfLink,
    content
  };
}

function makeTitleFromText(text) {
  const cleaned = String(text || "")
    .replace(/https?:\/\/\S+/g, "")
    .split(/\n+/)
    .map(v => v.trim())
    .filter(Boolean)[0] || "LinkedIn research post";

  return cleaned.length > 120 ? cleaned.slice(0, 117) + "..." : cleaned;
}

function extractFirstUrl(text) {
  const match = String(text || "").match(/https?:\/\/[^\s)"'>]+/);
  return match ? match[0] : "";
}

function extractDoiOrPdfLink(text) {
  const value = String(text || "");

  const doiUrl = value.match(/https?:\/\/(dx\.)?doi\.org\/[^\s)"'>]+/i);
  if (doiUrl) return doiUrl[0];

  const doi = value.match(/\b10\.\d{4,9}\/[-._;()/:A-Z0-9]+\b/i);
  if (doi) return `https://doi.org/${doi[0]}`;

  const pdf = value.match(/https?:\/\/[^\s)"'>]+\.pdf\b[^\s)"'>]*/i);
  if (pdf) return pdf[0];

  return "";
}

async function sha256Hex(value) {
  const buffer = await crypto.subtle.digest(
    "SHA-256",
    new TextEncoder().encode(String(value || ""))
  );

  return Array.from(new Uint8Array(buffer))
    .map(byte => byte.toString(16).padStart(2, "0"))
    .join("");
}

async function adminReindexResearchPapers(request, env) {
  if (!isAdmin(request, env)) {
    return json({ ok: false, error: "Unauthorized" }, 401);
  }

  const posts = await env.DB.prepare(`
    SELECT *
    FROM posts
    WHERE section = 'research'
      AND type = 'paper'
      AND status = 'published'
    ORDER BY datetime(created_at) DESC
  `).all();

  let indexed = 0;
  let legacyIndexed = 0;
  let failed = 0;
  const errors = [];

  for (const post of posts.results || []) {
    try {
      await indexResearchPaperPost(post, env);
      indexed++;
    } catch (error) {
      failed++;
      errors.push({
        id: post.id,
        title: post.title,
        source: "posts",
        error: error?.message || "Unknown error"
      });
    }
  }

  // v12 fix:
  // LinkedIn/BibTeX imports were stored directly in research_knowledge with post_id like linkedin_*,
  // so the old Reindex button did not refresh them. This caused title-only rows such as
  // "Source: LinkedIn post... title = {...}" to remain without abstract/DOI metadata.
  // Reindex now also learns these legacy rows by title/DOI using Crossref + Europe PMC,
  // with the original imported text as fallback.
  const legacyRows = await env.DB.prepare(`
    SELECT id, post_id, title, source_url, pdf_link, content
    FROM research_knowledge
    WHERE status = 'indexed'
      AND (
        post_id LIKE 'linkedin_%'
        OR content LIKE '%Source: LinkedIn post%'
        OR content LIKE '%title = {%'
        OR content LIKE '%title={%'
      )
    ORDER BY datetime(updated_at) DESC
    LIMIT 1000
  `).all();

  for (const row of legacyRows.results || []) {
    try {
      const didUpdate = await reindexLegacyLinkedInOrBibtexKnowledgeRow(row, env);
      if (didUpdate) legacyIndexed++;
    } catch (error) {
      failed++;
      errors.push({
        id: row.id,
        postId: row.post_id,
        title: row.title,
        source: "legacy_research_knowledge",
        error: error?.message || "Unknown error"
      });
    }
  }

  const totalPosts = posts.results?.length || 0;
  const totalLegacyRows = legacyRows.results?.length || 0;

  return json({
    ok: true,
    total: totalPosts + totalLegacyRows,
    postsTotal: totalPosts,
    legacyRowsTotal: totalLegacyRows,
    indexed,
    legacyIndexed,
    failed,
    errors: errors.slice(0, 20),
    message: `Reindexed ${indexed} research papers and ${legacyIndexed} LinkedIn/BibTeX knowledge rows. Failed: ${failed}`
  });
}

